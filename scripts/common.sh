#!/bin/bash
# 共享工具库 —— 供仓库内所有脚本 source 引用
#
# 用法：
#   source "$(dirname "${BASH_SOURCE[0]}")/common.sh"
#
# 提供：
#   - 彩色日志函数：log_info / log_ok / log_warn / log_error / log_step / log_banner
#   - 命令执行包装：run_cmd

# ---------- 颜色常量 ----------
_R='\033[0;31m'  # red
_G='\033[0;32m'  # green
_Y='\033[0;33m'  # yellow
_B='\033[0;34m'  # blue
_C='\033[0;36m'  # cyan
_W='\033[1;37m'  # bold white
_N='\033[0m'     # reset

# ---------- 日志函数 ----------
log_info()    { echo -e "${_C}  ℹ  ${_N}$*"; }
log_ok()      { echo -e "${_G}  ✓  ${_N}$*"; }
log_warn()    { echo -e "${_Y}  ⚠  ${_N}$*"; }
log_error()   { echo -e "${_R}  ✗  ${_N}$*" >&2; }
log_step()    { echo -e "${_W}  ▶  ${_N}$*"; }
log_banner()  {
    echo -e "${_B}════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════${_N}"
    echo -e "${_W}  $*${_N}"
    echo -e "${_B}════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════════${_N}"
}

# ---------- 命令执行包装 ----------
# run_cmd <描述> <命令...>
# 执行命令，成功输出 log_ok，失败输出 log_error 并退出
run_cmd() {
    local desc="$1"; shift
    log_info "${desc}"
    if "$@"; then
        log_ok "${desc} 完成"
    else
        log_error "${desc} 失败（exit $?）"
        exit 1
    fi
}